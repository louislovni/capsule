#!/usr/bin/env python3
"""Generates Core/pkcore/pk_profiles_gen.c from PokeDaisy's gamedata (GPL v3).

Usage: python3 tools/gen_profiles.py /path/to/pokedaisy/gamedata Core/pkcore/pk_profiles_gen.c
Only the handful of RAM addresses this app reads are kept.
"""
import sys, tomllib, pathlib

FIELDS = ["playerParty", "playerPartyCount", "enemyParty", "gMain",
          "saveBlock1Ptr", "saveBlock2Ptr", "pokemonStoragePtr"]
# Retail configs that carry no `port` key: config name -> (game code, revision)
RETAIL = {
    "firered_rev0": [("BPRE", 0)], "firered_rev1": [("BPRE", 1)],
    "leafgreen_rev0": [("BPGE", 0)], "leafgreen_rev1": [("BPGE", 1)],
    "emerald_retail": [("BPEE", 0)], "emerald_es": [("BPES", 0)], "emerald_de": [("BPED", 0)],
    "emerald_fr": [("BPEF", 0)], "emerald_it": [("BPEI", 0)], "emerald_ja": [("BPEJ", 0)],
    "ruby": [("AXVE", 1), ("AXVE", 2)], "sapphire": [("AXPE", 1), ("AXPE", 2)],
}

def main(src, dst):
    configs = {}
    for group in ("retail", "ports"):
        for f in sorted(pathlib.Path(src, "gen3", group).glob("*.toml")):
            data = tomllib.loads(f.read_text(encoding="utf-8"))
            for name, cfg in data.get("config", {}).items():
                configs[name] = cfg

    def resolve(name, seen=()):
        cfg = configs[name]
        out = {}
        base = cfg.get("base")
        if base and base in configs and base not in seen:
            out.update(resolve(base, seen + (name,)))
        out.update({k: v for k, v in cfg.items() if not isinstance(v, dict)})
        return out

    rows = []
    for name in configs:
        cfg = resolve(name)
        own = configs[name]
        if "port" in own:
            ids = [(own["port"][:4], int(own["port"][4:]))]
        elif name in RETAIL:
            ids = RETAIL[name]
        else:
            continue
        if "playerParty" not in cfg or "playerPartyCount" not in cfg:
            continue
        for code, rev in ids:
            rows.append((code, rev, name, cfg))
    rows.sort(key=lambda r: (r[0], r[1]))

    lines = ["/* GENERATED by tools/gen_profiles.py from PokeDaisy's gamedata (GPL v3,",
             " * https://github.com/lidor30/pokedaisy). Do not edit by hand. */",
             '#include "pkcore.h"', "",
             "const PKProfile pk_profiles[] = {"]
    for code, rev, name, cfg in rows:
        vals = ", ".join("0x%08X" % cfg.get(f, 0) for f in FIELDS)
        static = 1 if cfg.get("staticSaveBlocks") else 0
        lines.append('\t{ "%s", %d, %s, %d }, /* %s */' % (code, rev, vals, static, name))
    lines += ["};", "", "const size_t pk_profile_count = sizeof(pk_profiles) / sizeof(pk_profiles[0]);", ""]
    pathlib.Path(dst).write_text("\n".join(lines), encoding="utf-8")
    print("%d profiles" % len(rows))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
