/* Writes docs/dex.js: French names, types and base stats of species 1-649 for the web page.
 * cc -I Core/pkcore tools/gen_webdex.c Core/pkcore/*.c -o /tmp/gen_webdex && /tmp/gen_webdex > docs/dex.js */
#include "pkcore.h"
#include <stdio.h>

static void str(const char* s) {
	putchar('"');
	for (; s && *s; ++s) {
		if (*s == '"' || *s == '\\') putchar('\\');
		putchar(*s);
	}
	putchar('"');
}

int main(void) {
	printf("// Generated by tools/gen_webdex.c from pkcore's tables (names: PKHeX, stats and types: PokeAPI).\n");
	printf("window.CAPSULE_TYPES = [");
	for (unsigned t = 0; t < 17; ++t) {
		if (t) putchar(',');
		str(pk_nds_type_name(t));
	}
	printf("];\nwindow.CAPSULE_DEX = [null");
	for (unsigned dex = 1; dex <= 649; ++dex) {
		PKNDSBase base;
		pk_nds_base_stats(dex, &base);
		printf(",\n[");
		str(pk_nds_species_name(dex));
		printf(",%u,%u,[%u,%u,%u,%u,%u,%u]]", base.type1, base.type2, base.stats[0], base.stats[1], base.stats[2],
		       base.stats[3], base.stats[4], base.stats[5]);
	}
	printf("];\n");
	return 0;
}
